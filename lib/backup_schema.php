/** Read metadata only. Database names, row counts, next-ID counters and cardinality are excluded. */
function doyel_schema_inventory(PDO $pdo): array
{
    $schema = $pdo->query('SELECT DATABASE()')->fetchColumn();
    if (!is_string($schema) || $schema === '') throw new RuntimeException('No application schema selected.');
    $read = static function (string $sql) use ($pdo, $schema): array {
        $q = $pdo->prepare($sql);
        $q->execute([$schema]);
        $rows = $q->fetchAll(PDO::FETCH_ASSOC);
        foreach ($rows as &$row) foreach ($row as &$value) if ($value !== null) $value = (string)$value;
        return $rows;
    };
    $tables = $read('SELECT TABLE_NAME, TABLE_TYPE, ENGINE, TABLE_COLLATION, CREATE_OPTIONS FROM information_schema.TABLES WHERE TABLE_SCHEMA = ? ORDER BY TABLE_NAME');
    $columns = $read('SELECT TABLE_NAME, COLUMN_NAME, ORDINAL_POSITION, COLUMN_TYPE, IS_NULLABLE, COLUMN_DEFAULT, EXTRA, CHARACTER_SET_NAME, COLLATION_NAME, GENERATION_EXPRESSION FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = ? ORDER BY TABLE_NAME, ORDINAL_POSITION');
    $indexes = $read('SELECT TABLE_NAME, INDEX_NAME, NON_UNIQUE, SEQ_IN_INDEX, COLUMN_NAME, COLLATION, SUB_PART, NULLABLE, INDEX_TYPE, IS_VISIBLE, EXPRESSION FROM information_schema.STATISTICS WHERE TABLE_SCHEMA = ? ORDER BY TABLE_NAME, INDEX_NAME, SEQ_IN_INDEX');
    $foreignKeys = $read('SELECT k.TABLE_NAME, k.CONSTRAINT_NAME, k.ORDINAL_POSITION, k.COLUMN_NAME, k.REFERENCED_TABLE_SCHEMA, k.REFERENCED_TABLE_NAME, k.REFERENCED_COLUMN_NAME, r.UPDATE_RULE, r.DELETE_RULE, r.MATCH_OPTION FROM information_schema.KEY_COLUMN_USAGE k JOIN information_schema.REFERENTIAL_CONSTRAINTS r ON r.CONSTRAINT_SCHEMA = k.CONSTRAINT_SCHEMA AND r.TABLE_NAME = k.TABLE_NAME AND r.CONSTRAINT_NAME = k.CONSTRAINT_NAME WHERE k.CONSTRAINT_SCHEMA = ? ORDER BY k.TABLE_NAME, k.CONSTRAINT_NAME, k.ORDINAL_POSITION');
    foreach ($foreignKeys as &$key) $key['REFERENCED_TABLE_SCHEMA'] = $key['REFERENCED_TABLE_SCHEMA'] === $schema ? '@self' : '@external';
    unset($key);
    $checks = $read('SELECT t.TABLE_NAME, t.CONSTRAINT_NAME, t.ENFORCED, c.CHECK_CLAUSE FROM information_schema.TABLE_CONSTRAINTS t JOIN information_schema.CHECK_CONSTRAINTS c ON c.CONSTRAINT_SCHEMA = t.CONSTRAINT_SCHEMA AND c.CONSTRAINT_NAME = t.CONSTRAINT_NAME WHERE t.CONSTRAINT_SCHEMA = ? ORDER BY t.TABLE_NAME, t.CONSTRAINT_NAME');
    $triggers = $read('SELECT TRIGGER_NAME, EVENT_MANIPULATION, EVENT_OBJECT_TABLE, ACTION_TIMING, ACTION_STATEMENT FROM information_schema.TRIGGERS WHERE TRIGGER_SCHEMA = ? ORDER BY TRIGGER_NAME');
    return ['tables' => $tables, 'columns' => $columns, 'indexes' => $indexes, 'foreign_keys' => $foreignKeys, 'checks' => $checks, 'triggers' => $triggers];
}

function doyel_schema_fingerprint(PDO $pdo): string
{
    return hash('sha256', json_encode(doyel_schema_inventory($pdo), JSON_THROW_ON_ERROR | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES));
}

function doyel_schema_expected_fingerprint(): string
{
    return hash('sha256', json_encode(doyel_schema_expected_inventory(), JSON_THROW_ON_ERROR | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES));
}

function doyel_schema_assert(PDO $pdo): void
{
    if (!hash_equals(doyel_schema_expected_fingerprint(), doyel_schema_fingerprint($pdo))) {
        throw new RuntimeException('The database schema is not compatible with this application release.');
    }
}

